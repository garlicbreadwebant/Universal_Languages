const fs = require('node:fs');
const path = require('node:path');
const base = path.resolve(__dirname, '..');
const config = {
  lumena: {name: 'Lumena', tagline: 'Simple sounds. Clear connections.', description: 'An open-syllable language with predictable spelling and explicit grammar.', greeting: 'sali', example: 'mi tu lena Lumena.', translation: 'I am learning Lumena.', facts: ['14 letters', 'Open syllables', 'No inflection']},
  narela: {name: 'Narela', tagline: 'Familiar patterns. New possibilities.', description: 'A regular starter language with a practical vocabulary and room to grow.', greeting: 'sali', example: 'Mi du lena la nara nova.', translation: 'I am learning the new language.', facts: ['Regular verbs', 'Plural −n', 'Optional articles']}
};
const docs = {overview: 'README.md', pronunciation: 'PRONUNCIATION.md', grammar: 'GRAMMAR.md', lessons: 'LESSONS.md', design: 'DESIGN.md', changelog: 'CHANGELOG.md'};
for (const lang of Object.values(config)) {
  const folder = path.join(base, lang.name);
  const lines = fs.readFileSync(path.join(folder, 'lexicon.csv'), 'utf8').trim().split(/\r?\n/);
  const expected = `english,${lang.name.toLowerCase()},category,notes`;
  if (lines.shift() !== expected) throw Error(`Invalid CSV header: ${lang.name}`);
  lang.entries = lines.map(line => {
    const fields = line.split(',');
    if (fields.length !== 4 || fields.some(f => !f.trim() || f.includes('"'))) throw Error(`Invalid simple CSV row: ${line}`);
    const [english, word, category, notes] = fields;
    return {english, word, category, notes};
  });
  if (new Set(lang.entries.map(e => e.word)).size !== lang.entries.length) throw Error(`Duplicate words: ${lang.name}`);
  lang.documents = Object.fromEntries(Object.entries(docs).map(([key, file]) => [key, fs.readFileSync(path.join(folder, file), 'utf8')]));
}
const content = '// Generated by build-data.cjs; edit the language source folders.\nwindow.LANGUAGE_DATA = ' + JSON.stringify(config, null, 2).replaceAll('<', '\\u003c') + ';\n';
const destination = path.join(__dirname, 'data.js');
const siteDocs = Object.fromEntries(['privacy', 'cookies', 'terms', 'changelog'].map(name => [name, fs.readFileSync(path.join(__dirname, `${name}.md`), 'utf8').replace(/\r\n/g, '\n')]));
const siteContent = '// Generated by build-data.cjs from website policy and changelog Markdown.\nwindow.SITE_DOCUMENTS = ' + JSON.stringify(siteDocs, null, 2).replaceAll('<', '\\u003c') + ';\n';
const siteDestination = path.join(__dirname, 'site-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content) throw Error('Website content is stale. Run node website/build-data.cjs');
  if (!fs.existsSync(siteDestination) || fs.readFileSync(siteDestination, 'utf8').replace(/\r\n/g, '\n') !== siteContent) throw Error('Website policy snapshot is stale. Run node website/build-data.cjs');
  console.log('OK: website snapshot matches both language folders.');
} else {
  fs.writeFileSync(destination, content);
  fs.writeFileSync(siteDestination, siteContent);
  console.log('Built website snapshot for Lumena and Narela.');
}
